import fs from 'node:fs/promises';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { loadProject, saveProject } from './reviewState.js';
const file = path.resolve(process.argv[2]);
const project = await loadProject(file);
if (!project.review || project.review.submission_started_at) throw new Error('Thumbnail requires a rendered, unsubmitted video.');
const exec = promisify(execFile);
const { stdout } = await exec('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', project.review.video_path]);
const target = path.join(path.dirname(project.review.video_path), 'thumbnail.jpg');
const custom = project.youtube_metadata as { thumbnail_source_path?: string; thumbnail_timestamp_seconds?: number } | undefined;
const source = custom?.thumbnail_source_path || project.review.video_path;
const timestamp = custom?.thumbnail_timestamp_seconds ?? Number(stdout.trim()) * 0.35;
const seek = /\.(png|jpe?g|webp)$/i.test(source) ? [] : ['-ss', String(timestamp)];
await exec('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', ...seek, '-i', source, '-frames:v', '1', '-vf', 'scale=1280:720:force_original_aspect_ratio=decrease,pad=1280:720:(ow-iw)/2:(oh-ih)/2', '-q:v', '2', target]);
if ((await fs.stat(target)).size > 2 * 1024 ** 2) throw new Error('Thumbnail exceeds 2 MB.');
project.review.thumbnail_path = target;
await saveProject(file, project);
console.log(JSON.stringify({ thumbnail: target }));
